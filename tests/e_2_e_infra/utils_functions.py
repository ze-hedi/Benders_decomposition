"""Shared helpers for the cucumber end-to-end steps.

Adapted from antares-xpansion tests/end_to_end/utils_functions.py:
 - configuration comes from build_config.yaml (generated by CMake from
   build_config.yaml.in), with environment variable overrides
 - no xpress dependency, MPI launcher kept as a no-op placeholder
"""

import json
import os
import shutil
import sys
from pathlib import Path

import yaml

# tests/e_2_e_infra
INFRA_ROOT = Path(os.path.abspath(__file__)).parent
# repository root
REPO_ROOT = INFRA_ROOT.parent.parent
CONFIG_FILE_PATH = INFRA_ROOT / "build_config.yaml"

# Fallback values used when build_config.yaml has not been generated yet
_DEFAULTS = {
    "benders": str(REPO_ROOT / "build" / "benders"),
}


def get_conf(key: str):
    """Read a configuration entry.

    Resolution order:
      1. environment variable E2E_<KEY> (upper case)
      2. build_config.yaml (generated by CMake)
      3. built-in default
    """
    env_value = os.environ.get(f"E2E_{key.upper()}")
    if env_value:
        return env_value

    if CONFIG_FILE_PATH.is_file():
        with open(CONFIG_FILE_PATH) as file:
            content = yaml.full_load(file)
        if content is None:
            raise RuntimeError("Please check build_config.yaml, content is empty")
        value = content.get(key)
        if value is not None and not str(value).startswith("@"):
            return value

    if key in _DEFAULTS:
        return _DEFAULTS[key]
    raise RuntimeError(f"Key '{key}' not found in {CONFIG_FILE_PATH} and no default exists")


def get_benders_executable() -> Path:
    return Path(get_conf("benders"))


def get_mpi_command(nproc: int = 1, allow_run_as_root: bool = False):
    """MPI launcher prefix. Empty for a single process (current Benders CLI
    is sequential); kept as an indirection point for a future MPI build."""
    if nproc <= 1:
        return []
    nproc_str = str(nproc)
    if sys.platform.startswith("win32"):
        return ["mpiexec", "-n", nproc_str]
    if sys.platform.startswith("linux"):
        command = ["mpirun"]
        if allow_run_as_root:
            command.append("--allow-run-as-root")
        command += ["-np", nproc_str, "--oversubscribe"]
        return command
    raise RuntimeError(f"Unsupported platform for MPI launch: {sys.platform}")


def read_json_file(json_path) -> dict:
    with open(json_path, "r") as file:
        return json.load(file)


def write_json_file(json_path, content) -> None:
    with open(json_path, "w") as file:
        json.dump(content, file, indent=4)


def remove_outputs(study_path: Path) -> None:
    output_path = study_path / "output"
    if output_path.is_dir():
        shutil.rmtree(output_path)
    output_path.mkdir(parents=True)


def resolve_study_path(study: str) -> Path:
    """Resolve a study path written in a feature file.

    Relative paths are resolved from the infra root (tests/e_2_e_infra), e.g.
    "data_test/mini_instance_LP" -> tests/e_2_e_infra/data_test/mini_instance_LP.
    """
    path = Path(study)
    return path if path.is_absolute() else INFRA_ROOT / path
